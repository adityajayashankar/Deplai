import { chromium } from '../preview-proof/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import {readFile, writeFile} from 'node:fs/promises';
import {randomBytes} from 'node:crypto';
const [origin, worktree]=process.argv.slice(2);
if(!/^https:\/\/p-[a-f0-9]{32}\.localhost:\d+$/.test(origin)) throw Error('Private preview origin required');
const browser=await chromium.launch({headless:true});
const results={};
try {
 const context=await browser.newContext({ignoreHTTPSErrors:true});
 const page=await context.newPage(); await page.goto(origin);
 await page.getByLabel('Email').fill('preview@example.invalid');
 await page.getByLabel('Password').fill(randomBytes(20).toString('hex'));
 await page.getByRole('button',{name:'Register',exact:true}).click();
 await page.getByRole('status').filter({hasText:'register complete'}).waitFor();
 await page.getByRole('button',{name:'Log in',exact:true}).click();
 await page.getByRole('status').filter({hasText:'login complete'}).waitFor();
 const cookie=(await context.cookies(origin+'/api/')).find(c=>c.name==='preview_session');
 assert.ok(cookie?.httpOnly&&cookie.secure&&cookie.sameSite==='Lax'&&cookie.domain===new URL(origin).hostname);
 results.cookie='PASS';
 await page.getByLabel('Note').fill('durable preview record');
 await page.getByRole('button',{name:'Create record',exact:true}).click();
 await page.getByRole('listitem').filter({hasText:'durable preview record'}).waitFor();
 await page.reload();
 await page.getByRole('button',{name:'Load records',exact:true}).click();
 await page.getByRole('listitem').filter({hasText:'durable preview record'}).waitFor();
 results.crud='PASS';
 const source=worktree+'/frontend/src.jsx';
 await writeFile(source,(await readFile(source,'utf8')).replace('Preview fixture','Preview edited'));
 await page.getByRole('heading',{name:'Preview edited',exact:true}).waitFor({timeout:15000});
 results.frontend_reload='PASS';
 const backend=worktree+'/backend/server.mjs';
 await writeFile(backend,(await readFile(backend,'utf8')).replace('version-one','version-two'));
 await page.waitForFunction(async()=>{try{return (await fetch('/api/version').then(r=>r.json())).version==='version-two';}catch{return false;}},undefined,{timeout:15000});
 results.backend_reload='PASS';
 const other=origin.replace(new URL(origin).hostname,'p-'+ '0'.repeat(32)+'.localhost');
 assert.equal((await context.cookies(other+'/api/')).length,0); results.cookie_isolation='PASS';
 await context.close();
} finally {await browser.close(); console.log(JSON.stringify(results));}
